let ready = false;

export async function initI18n() {
  await i18next.init({
    lng: resolvedLanguage(),
    fallbackLng: 'en',
    resources: { zh: { translation: zh }, en: { translation: en } },
    interpolation: { escapeValue: false },
    returnNull: false
  });
  ready = true;
  document.documentElement.lang = currentLang() === 'zh' ? 'zh-CN' : 'en';
}

export function t(key: string, opts: any = {}): string {
  if (!ready) return key;
  return i18next.t(key, opts) as string;
}

export function currentLang() { return i18next.language || resolvedLanguage(); }

export async function setLanguage(lang) {
  set('language', lang);
  await i18next.changeLanguage(lang === 'auto' ? resolvedLanguage() : lang);
  document.documentElement.lang = currentLang() === 'zh' ? 'zh-CN' : 'en';
  emit('language:changed', currentLang());
}

